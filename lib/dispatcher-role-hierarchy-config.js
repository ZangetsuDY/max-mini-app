function safeParse(value, fallback) {
  if (value === null || value === undefined || value === "") return fallback;
  if (typeof value === "object") return value;
  try { return JSON.parse(value); }
  catch { return fallback; }
}

function cleanText(value, maxLength = 180) {
  return String(value || "")
    .trim()
    .replace(/\s+/g, " ")
    .slice(0, maxLength);
}

function normalizeRoles(values) {
  if (!Array.isArray(values)) return [];
  return [
    ...new Set(
      values
        .map((value) => cleanText(value, 180))
        .filter(Boolean)
        .slice(0, 220)
    )
  ];
}

function normalizeEntry(value) {
  return {
    mainRole: cleanText(value?.mainRole, 180),
    subordinateRoles: normalizeRoles(value?.subordinateRoles),
    updatedAt: value?.updatedAt || null,
    updatedBy: value?.updatedBy || null
  };
}

function defaultForUnit(unitId) {
  const value = DEFAULT_UNIT_HIERARCHY[String(unitId || "")];
  return value
    ? {
        mainRole: value.mainRole,
        subordinateRoles: [...value.subordinateRoles]
      }
    : {
        mainRole: "",
        subordinateRoles: []
      };
}

async function readOverrides() {
  if (!isRuntimeStoreConfigured()) return {};

  try {
    const raw = await redisCommand("GET", CONFIG_KEY);
    const parsed = safeParse(raw, {});
    return parsed && typeof parsed === "object" && !Array.isArray(parsed)
      ? parsed
      : {};
  } catch (error) {
    console.error("Не удалось загрузить иерархию диспетчерских ролей:", error);
    return {};
  }
}

async function writeOverrides(overrides) {
  if (!isRuntimeStoreConfigured()) {
    throw new Error("Хранилище состояния не подключено");
  }

  await redisCommand(
    "SET",
    CONFIG_KEY,
    JSON.stringify(overrides)
  );
}

export function getDispatcherRoleHierarchyCatalog() {
  return ROLE_HIERARCHY_CATALOG.map((item) => ({
    mainRole: item.mainRole,
    subordinateRoles: [...item.subordinateRoles]
  }));
}

export async function getDispatcherRoleHierarchyConfig() {
  const [overrides, structure] = await Promise.all([
    readOverrides(),
    getDispatcherStructure()
  ]);

  return structure.units.map((unit) => {
    const defaultValue = defaultForUnit(unit.id);
    const hasOverride = Object.prototype.hasOwnProperty.call(
      overrides,
      unit.id
    );
    const override = hasOverride
      ? normalizeEntry(overrides[unit.id])
      : null;
    const effective = override || defaultValue;

    return {
      unitId: unit.id,
      groupId: unit.groupId,
      unitName: unit.name,
      mainRole: effective.mainRole || "",
      subordinateRoles: normalizeRoles(effective.subordinateRoles),
      defaultMainRole: defaultValue.mainRole || "",
      defaultSubordinateRoles: normalizeRoles(defaultValue.subordinateRoles),
      customized: hasOverride,
      updatedAt: override?.updatedAt || null,
      updatedBy: override?.updatedBy || null
    };
  });
}

export async function getDispatcherUnitRoleHierarchy(unitId) {
  const unit = await getDispatcherUnitRuntime(
    String(unitId || "").trim()
  );

  if (!unit) return null;

  const all = await getDispatcherRoleHierarchyConfig();
  return all.find((item) => item.unitId === unit.id) || null;
}

export async function setDispatcherUnitRoleHierarchy({
  unitId,
  mainRole,
  subordinateRoles,
  actor
}) {
  const unit = await getDispatcherUnitRuntime(
    String(unitId || "").trim()
  );

  if (!unit) {
    throw new Error("РЭС/район не найден");
  }

  const overrides = await readOverrides();

  overrides[unit.id] = {
    mainRole: cleanText(mainRole, 180),
    subordinateRoles: normalizeRoles(subordinateRoles),
    updatedAt: new Date().toISOString(),
    updatedBy: {
      username: String(actor?.username || ""),
      fullName: String(actor?.fullName || "")
    }
  };

  await writeOverrides(overrides);
  return getDispatcherUnitRoleHierarchy(unit.id);
}

export async function resetDispatcherUnitRoleHierarchy({
  unitId
}) {
  const unit = await getDispatcherUnitRuntime(
    String(unitId || "").trim()
  );

  if (!unit) {
    throw new Error("РЭС/район не найден");
  }

  const overrides = await readOverrides();
  delete overrides[unit.id];
  await writeOverrides(overrides);

  return getDispatcherUnitRoleHierarchy(unit.id);
}
